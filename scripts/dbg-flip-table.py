#!/usr/bin/env python3
"""Curated evidence table for the TU_DEBUG render-mode arms of journal 40.16 (queue 22).

Writes `results/games/re4/dbg-flip-and-messages.txt`: per arm, the driver's own flag-delivery line, the
histogram of the messages that arm printed, the `TU_DEBUG_FILE` flip rows of the `dbg-file`
session, and p25 fps in fixed windows.

    scripts/dbg-flip-table.py > results/games/re4/dbg-flip-and-messages.txt

Reads only committed files: `results/games/re4/dbg-<arm>/fdperf-raw.txt`, `results/games/re4/fps-dbg-<arm>.csv`,
and the raw run logs `results/raw/game-patched-dbg-<arm>.log` (gitignored, regenerated by
`/tmp/opencode/chain22.sh` with `TAG=dbg-<arm>`).  The message histogram is a count of fixed
substrings, so it also says which strings it asked about and which of them are absent.

fps windows are seconds of MangoHud's own clock (`elapsed` in the csv), which starts about 35 s
after the chain's launch line; steady gameplay is t>=40.  Tile and VSC columns are medians over
samples whose `PERF_CP_ALWAYS_COUNT` is within 1 % of 680 MHz (the window rule of journal 40.13,
Correction 2).
"""
import csv
import statistics
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from fdperf_sections import load

ARMS = ["dbg-perf", "dbg-file", "dbg-gmem", "dbg-sysmem"]
PIN = 680e6

# The message strings this table asks about.  Written out, because "count of nothing" and
# "count of zero" are different claims: the render-mode reason strings of journal 40.15 are in
# the list precisely to record that the driver never prints them.
MESSAGES = [
    "Disabling LRZ because 'FS writes depth or has side-effects",
    "Disabling LRZ because 'Depth write + ALWAYS/NOT_EQUAL'",
    "Skipping LRZ due to ALWAYS/NOT_EQUAL",
    "Disabling UBWC on ",
    "[GMEM] loads total: 0",
    "[GMEM] loads total:",
    "Disabling gmem",
    "VK_IMAGE_COMPRESSION_DISABLED_EXT",
    "force_render_mode",
    "Can't fit attachments into gmem",
    "Uses tessellation shaders",
    "Render area is empty",
    "Non-framebuffer-space barrier",
    "Too many tiles and HW binning is not possible",
]


def fps_windows(path, windows):
    rows = []
    lines = open(path).read().splitlines()
    for r in csv.DictReader(lines[2:]):
        try:
            rows.append((float(r["elapsed"]) / 1e9, float(r["fps"])))
        except (ValueError, KeyError):
            continue
    out = []
    for lo, hi in windows:
        v = [x for t, x in rows if lo <= t < hi]
        out.append((lo, hi, len(v), statistics.quantiles(v, n=4)[0] if v else None))
    return out


def tile_rows(path):
    samples, _un, _dr = load(path)
    out = []
    for s in samples:
        clk = s.get("PERF_CP_ALWAYS_COUNT")
        out.append((s["t"], s.get("PERF_VSC_INPUT_TILES"), s.get("PERF_VSC_BUSY_CYCLES"), clk))
    return out


def main() -> int:
    print("# TU_DEBUG render-mode arms, journal 40.16/40.17 (queues 22, 23).  Regenerate:")
    print("#   scripts/dbg-flip-table.py > results/games/re4/dbg-flip-and-messages.txt")
    print("# game: Resident Evil 4 Gold Edition (re4.exe), D3D12 via vkd3d-proton 3.1.0,")
    print("#       2560x1440, proton-cachyos-11.0-arm64; see results/games/README.md")
    print("# driver: build/out/libvulkan_freedreno.so sha256 4c3cdb210082 (ship stack)")
    print("# delta per arm: the TU_DEBUG value in its delivery line, nothing else")
    print("# sampler: tools/fdperf/fdperf.cfg-tse3 for the four dbg arms")
    print("")

    for arm in ARMS:
        log = f"results/raw/game-patched-{arm}.log"
        print(f"===== {arm}")
        try:
            lines = open(log, errors="replace").read().splitlines()
        except OSError as e:
            print(f"  log unavailable: {e}")
            continue
        print(f"  log lines: {len(lines)}")
        dl = [l for l in lines if "TU_DEBUG=0x" in l or "Watching TU_DEBUG_FILE" in l]
        print("  flag delivery (verbatim):")
        seen = set()
        for l in dl:
            if l not in seen:
                print(f"    {l}")
                seen.add(l)
        counts = []
        for m in MESSAGES:
            n = sum(1 for l in lines if m in l)
            counts.append((m, n))
        counts.sort(key=lambda x: -x[1])
        print("  message counts, substring match (0 means the string never appears in this arm):")
        for m, n in counts:
            print(f"    {n:6d}  {m}")
        print("")

    print("===== the TU_DEBUG_FILE flip inside one session (arm dbg-file)")
    print("# chain+ s, tiles, VSC busy cycles, median clock of that sample")
    print("# flag file written at chain+85.0 s, blanked at chain+175.0 s (/tmp/opencode/chain22.sh)")
    print("# sampler's first sample at chain+64.9 s; samples are ~2.1 s apart")
    CHAIN0 = 1795307283.0
    for t, tiles, busy, clk in tile_rows("results/games/re4/dbg-file/fdperf-raw.txt"):
        rel = t - CHAIN0
        if 78.0 <= rel <= 92.0 or rel >= 168.0:
            mhz = f"{clk/1e6:.0f}" if clk else "-"
            print(f"chain+{rel:6.1f}  tiles={tiles:>12,}  vscbusy={busy:>12,}  {mhz} MHz")
    print("")

    print("===== p25 fps per window, seconds of MangoHud's own clock")
    print("| arm | window | n | p25 fps |")
    print("|---|---|---|---|")
    windows = [(70, 84), (95, 150), (150, 170)]
    for arm in ARMS:
        for lo, hi, n, p in fps_windows(f"results/games/re4/fps-{arm}.csv", windows):
            print(f"| {arm} | {lo}-{hi} | {n} | {'-' if p is None else f'{p:.2f}'} |")
    print("")
    print("===== steady-window tile and VSC columns (pinned-clock samples only)")
    print("| arm | counter window, chain+ s | pinned samples | tiles median/s | windows with tiles | VSC busy % of core |")
    print("|---|---|---|---|---|---|")
    # dbg-file changes mode inside the session, so its counters are read over the flipped stretch
    # only; the other three arms are constant over the run and are read whole.
    windows2 = {arm: (None, None) for arm in ARMS}
    windows2["dbg-file"] = (85.0, 175.0)
    for arm in ARMS:
        rows = tile_rows(f"results/games/re4/{arm}/fdperf-raw.txt")
        lo, hi = windows2[arm]
        fmt = "whole run" if lo is None else f"{lo:.0f}-{hi:.0f}"
        if lo is not None:
            rows = [r for r in rows if lo <= r[0] - CHAIN0 <= hi]
        pin = [r for r in rows if r[3] and abs(r[3] - PIN) <= 0.01 * PIN]
        tiles = [r[1] for r in pin if r[1] is not None]
        busy = [r[2] for r in pin if r[2] is not None]
        always = [r[3] for r in pin]
        if not tiles:
            print(f"| {arm} | {fmt} | 0/{len(rows)} | NOT MEASURED | - | - |")
            continue
        med = statistics.median(tiles)
        nonzero = sum(1 for x in tiles if x > 1000)
        pct = 100.0 * statistics.median(busy) / statistics.median(always)
        print(f"| {arm} | {fmt} | {len(pin)}/{len(rows)} | {med:,.0f} | {nonzero} of {len(tiles)} | {pct:.2f} |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
