#!/bin/bash
# Generate tests/rp6-vkd3d-sparse-xmc_spv.h from the two XMC read shaders
# (in the glslang container, same recipe as gen-tp-write-spv.sh):
#
#   podman run --rm -v $PWD/tests:/work:z localhost/mesa-build-fedora44-wsi-glslang-vulkan \
#       bash /work/gen-xmc-spv.sh
#
# Both shaders read a 64-bit integer view of one image and write the raw words out;
# see tests/rp6-vkd3d-sparse-xmc_u32x4.glsl for what probe XMC asks with them.
#
# -S comp is not decoration: glslang classifies a source by its ending and does not
# know ".glsl" (the .comp shaders elsewhere need no -S), so without it the tool prints
# its usage and exits 1.  glslangValidator here is the one in
# localhost/mesa-build-fedora44-wsi-glslang-vulkan; the older cast_*.glsl shaders in
# tests/ were built with glslc, which that image does not have.
set -euxo pipefail
cd /work
{
    echo "/* Generated by scripts/gen-xmc-spv.sh (do not edit):"
    echo " *   glslangValidator -V rp6-vkd3d-sparse-xmc_u32x4.glsl  -> xmc_u32x4_spv"
    echo " *   glslangValidator -V rp6-vkd3d-sparse-xmc_u32g32.glsl -> xmc_u32g32_spv"
    echo " */"
} > /tmp/xmc_head.h
for pair in "u32x4:rp6-vkd3d-sparse-xmc_u32x4.glsl" "u32g32:rp6-vkd3d-sparse-xmc_u32g32.glsl"; do
    name="${pair%%:*}"
    src="${pair#*:}"
    glslangValidator -S comp -V "$src" -o "/tmp/xmc_$name.spv"
    {
        echo
        echo "/* $src: reads a 64-bit integer view, writes the raw words. */"
        echo "static const uint32_t xmc_${name}_spv[] = {"
        od -A n -t u4 -v "/tmp/xmc_$name.spv" \
            | tr -s ' \t' ' ' | sed 's/^ //; s/ $//; s/ /, /g; s/$/,/' | sed '$ s/,$//'
        echo "};"
    } >> /tmp/xmc_body.h
done
cat /tmp/xmc_head.h /tmp/xmc_body.h > /work/rp6-vkd3d-sparse-xmc_spv.h
rm -f /tmp/xmc_body.h
head -4 /work/rp6-vkd3d-sparse-xmc_spv.h
grep -c "" /work/rp6-vkd3d-sparse-xmc_spv.h
