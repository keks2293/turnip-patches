#!/bin/bash
# Generate tests/rp6-vkd3d-sparse-xr64_spv.h from the two XR64 shaders
# (in the glslang container, same recipe as gen-xmc-spv.sh):
#
#   podman run --rm -v "$PWD/tests":/work:z -v "$PWD/scripts":/scripts:z \
#       localhost/mesa-build-fedora44-wsi-glslang-vulkan bash /scripts/gen-xr64-spv.sh
#
# Both shaders address one image as a r64ui storage image; see
# tests/rp6-vkd3d-sparse-xr64_load.glsl for why the storage path is the only one
# available for this member of the class.
#
# -S comp is required for the same reason as in gen-xmc-spv.sh: glslang decides
# the stage from the file name and does not know ".glsl".
set -euxo pipefail
cd /work
{
    echo "/* Generated by scripts/gen-xr64-spv.sh (do not edit):"
    echo " *   glslangValidator -V rp6-vkd3d-sparse-xr64_load.glsl   -> xr64_load_spv"
    echo " *   glslangValidator -V rp6-vkd3d-sparse-xr64_atomic.glsl -> xr64_atomic_spv"
    echo " */"
} > /tmp/xr64_head.h
for pair in "load:rp6-vkd3d-sparse-xr64_load.glsl" "atomic:rp6-vkd3d-sparse-xr64_atomic.glsl"; do
    name="${pair%%:*}"
    src="${pair#*:}"
    glslangValidator -S comp -V "$src" -o "/tmp/xr64_$name.spv"
    {
        echo
        echo "/* $src: r64ui storage image, ${name} side. */"
        echo "static const uint32_t xr64_${name}_spv[] = {"
        od -A n -t u4 -v "/tmp/xr64_$name.spv" \
            | tr -s ' \t' ' ' | sed 's/^ //; s/ $//; s/ /, /g; s/$/,/' | sed '$ s/,$//'
        echo "};"
    } >> /tmp/xr64_body.h
done
cat /tmp/xr64_head.h /tmp/xr64_body.h > /work/rp6-vkd3d-sparse-xr64_spv.h
rm -f /tmp/xr64_body.h
head -4 /work/rp6-vkd3d-sparse-xr64_spv.h
grep -c "" /work/rp6-vkd3d-sparse-xr64_spv.h
