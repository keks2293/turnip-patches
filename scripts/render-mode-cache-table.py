#!/usr/bin/env python3
"""The render-mode ladder on two different frames: the game's Shadow Cache off and on.

    scripts/render-mode-cache-table.py > results/games/re4/render-mode-two-frames.txt

Journal 40.16/40.18 built the ladder (forced sysmem / driver default / GMEM / GMEM + forced
binning) while RE4 ran with `AppShadowCache=0`.  Journal 40.19 showed that setting is worth 49 % of
the frame's primitives, so the ladder had been measured on a frame carrying 16.7 M primitives and
not on the game's cheaper one.  This table puts the two ladders side by side to answer queue 24:
does "GMEM is worse in both of its forms" survive when the shadow redraw is gone?

Reads only committed files: `results/games/re4/<arm>/fdperf-raw.txt`, `results/games/re4/fps-<arm>.csv`
and the delivery line `TU_DEBUG=0x...` that `scripts/run-game.sh` records in the curated run log
`results/games/re4/game-patched-<arm>.log` - the flag is quoted as the driver reported it, not as the
chain wrote it.  The `default` rows have no delivery line because no TU_DEBUG was set.

Rules: counter columns are means over 1 s windows within `t_rel` 20-105 s whose
`PERF_CP_ALWAYS_COUNT` is within 1 % of the pinned 680 MHz; fps is p25 of MangoHud's `elapsed` over
95-150 s (journal 40's steady stretch); `A7XX_PERF_VSC_INPUT_TILES` has no verified unit (journal
40.13), so only the 0-versus-non-zero and the order of magnitude are quotable.
"""
import csv
import os
import statistics
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from fdperf_sections import load, window

PIN = 680e6
LO, HI = 20, 105
FPS_WINDOW = (95, 150)

# (arm, frame, mode label) - frame names the value of the game's AppShadowCache in that run.
ARMS = [
    ("dbg-sysmem",  "cache off", "forced sysmem"),
    ("dbg-perf",    "cache off", "driver default"),
    ("gmem-nobin",  "cache off", "GMEM, binning not forced"),
    ("dbg-gmem",    "cache off", "GMEM + forced binning"),
    ("sc-sysmem",   "cache on",  "forced sysmem"),
    ("sc-default",  "cache on",  "driver default"),
    ("sc-gmem",     "cache on",  "GMEM, binning not forced"),
    ("sc-forcebin", "cache on",  "GMEM + forced binning"),
]


def delivery(arm):
    """The driver's own line `TU: info: TU_DEBUG=0x...`.  The curated log first; the raw run log
    (gitignored, regenerated by the chain) is the fallback for the arms that predate curation, and
    then the cell says so - a number copied from a file that is not in git is still marked."""
    for path, mark in ((f"results/games/re4/game-patched-{arm}.log", ""),
                       (f"results/raw/game-patched-{arm}.log", " (raw log, not in git)")):
        if not os.path.exists(path):
            continue
        for line in open(path, errors="replace"):
            if "TU_DEBUG=0x" in line:
                return line.strip().split("TU_DEBUG=")[1].split()[0] + mark
    return "NOT RECORDED"


def fps_p25(arm):
    path = f"results/games/re4/fps-{arm}.csv"
    if not os.path.exists(path):
        return None
    rows = open(path).read().splitlines()[2:]
    v = []
    for r in csv.DictReader(rows):
        try:
            t, f = float(r["elapsed"]) / 1e9, float(r["fps"])
        except (KeyError, TypeError, ValueError):
            continue
        if FPS_WINDOW[0] <= t < FPS_WINDOW[1] and 0.5 < f < 1000:
            v.append(f)
    return sorted(v)[len(v) // 4] if v else None


def counters(arm):
    path = f"results/games/re4/{arm}/fdperf-raw.txt"
    if not os.path.exists(path):
        return {}
    samples, _un, _dr = load(path)
    win = [s for s in window(samples, LO, HI)
           if s.get("PERF_CP_ALWAYS_COUNT") and abs(s["PERF_CP_ALWAYS_COUNT"] - PIN) / PIN < 0.01]

    def mean(key):
        v = [s[key] for s in win if isinstance(s.get(key), (int, float))]
        return statistics.mean(v) if v else None

    return {
        "n": len(win),
        "tiles": mean("PERF_VSC_INPUT_TILES"),
        "vsc": mean("PERF_VSC_BUSY_CYCLES"),
        "tse_in": mean("PERF_TSE_INPUT_PRIM"),
        "vpc": mean("PERF_VPC_BUSY_CYCLES"),
    }


def main():
    print("# Render-mode ladder measured on two frames of Resident Evil 4 Gold Edition (re4.exe,")
    print("#       D3D12 via vkd3d-proton 3.1.0, 2560x1440).  Registry: results/games/README.md")
    print("# driver: build/out/libvulkan_freedreno.so sha256 4c3cdb210082 (ship stack) in every arm;")
    print("#       frame 'cache off' = AppShadowCache=0 (journals 40.16/40.18), 'cache on' = 1 (chain27)")
    print("# sampler: tools/fdperf/fdperf.cfg-tse3; counter window t_rel 20-105 s at the pinned clock;")
    print("#       fps = p25 over MangoHud elapsed 95-150 s")
    print("# regenerate: scripts/render-mode-cache-table.py > results/games/re4/render-mode-two-frames.txt")
    print("")
    print("| frame | mode | TU_DEBUG as delivered | p25 fps | TSE in M/s | prims/frame | VSC tiles /s | VSC busy % | VPC busy % | windows |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for arm, frame, mode in ARMS:
        c = counters(arm)
        p25 = fps_p25(arm)

        def num(v, fmt="%8.2f"):
            return fmt % v if v is not None else "     n/a"

        prims_frame = c.get("tse_in") / p25 / 1e6 if c.get("tse_in") and p25 else None
        vsc = 100.0 * c["vsc"] / PIN if c.get("vsc") else None
        vpc = 100.0 * c["vpc"] / PIN if c.get("vpc") else None
        print(f"| {frame} | {mode} | {delivery(arm)} | {num(p25, '%7.2f')} |"
              f" {num(c.get('tse_in', 0) / 1e6 if c.get('tse_in') else None)} |"
              f" {num(prims_frame, '%6.2f')} M | {num(c.get('tiles', 0) / 1e6 if c.get('tiles') else None, '%8.2f')} |"
              f" {num(vsc, '%6.2f')} | {num(vpc, '%6.2f')} | {c.get('n', 0)} |")
    print("")
    print("`prims/frame` divides the per-second TSE input rate by the p25 fps of the same arm; the VSC")
    print("tile counter has no verified unit (journal 40.13), it is here as a yes/no on binning starting.")


if __name__ == "__main__":
    main()
