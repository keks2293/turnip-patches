#!/usr/bin/env python3
"""Does the VPC attribute-buffer carve-out do anything on A740? Read the arms of run-attrbuf-sweep.sh.

    scripts/attrbuf-table.py                          # every dir under results/synthetics/attrbuf
    scripts/attrbuf-table.py results/synthetics/attrbuf/*/
    scripts/attrbuf-table.py --pair prop-48k          # one pair only

The committed output is results/synthetics/attrbuf/table.txt (regenerated by the first form);
the sweep's directory is empty of arms today, so it prints the 23.11 smoke profile and no pair.

Why the table is a pair table and not a list of arm profiles.  Raising
`gmem_vpc_attr_buf_size` to S does two things at once: `emit_vpc_attr_buf()` writes
VPC_ATTR_BUF_GMEM_SIZE/_BASE and PC_ATTR_BUF_GMEM_SIZE, and it takes 6*S bytes off usable GMEM
(`fd6_gmem_cache.h:108-109`, `num_ccu = 6` for FD740), which by itself changes the work per bin.
So `scripts/run-attrbuf-sweep.sh` runs every prop arm twice: `prop(S)` with the three register
writes, and `ctrl(6S)` with `TU_GMEM` reduced by the same 6*S bytes and no writes.  The pair has
the same usable GMEM and the same CCU offsets by construction, so `prop - ctrl` is the effect of
the registers and nothing else.  A reader that printed nine arm profiles would invite exactly the
comparison the control arm exists to forbid - `prop-48k - base` is registers plus 288 KiB - which
is why the decision columns are only ever printed as a difference inside a pair.

The pairing is not guessed from numbers.  The names encode it (`prop-<S/1024>k` is paired with
`ctrl-<6S/1024>k`, and the `-loop64` suffix survives), and the meta.txt of both arms is checked
against the runner's own `gmem_kernel` line: `ctrl.tu_gmem` must be `gmem_kernel - 6*S`, and the
prop arm must carry `TU_FORCE_PROPS=has_gmem_vpc_attr_buf` plus
`FD_DEV_FEATURES=gmem_vpc_attr_buf_size=S`.  A pair whose arithmetic cannot be checked (queue 36:
`MSM_PARAM_GMEM_SIZE` answers EINVAL on this kernel, so the runner has no `gmem_kernel` to write)
is printed `UNVERIFIED`, not accepted silently; a prop arm with no same-TU_GMEM control is printed
`UNPAIRED` and its difference to `base` is not computed at all.  `prop-128k-loop64` and
`base-loop64` are such a case today: the slow-drain regime has no control arm in the committed
sweep, so their difference mixes the register writes with a 768 KiB carve
(docs/plan-next-checks.md item 43).

Units, because the cfg's columns are not all rates.  A cycle counter is printed as its ratio to
that window's own `CP_ALWAYS_COUNT` (`cycles/clock`), which is clock-free: 1.000 is one core for
the whole window, and a counter that counts across lanes reads `11.6` (the smoke run's
`VFD_STALL_CYCLES_VPC_ALLOC`).  An event counter is printed per delivered vertex
(`PERF_VFD_TOTAL_VERTICES` in the same window): the probe's mesh is 24576 independent triangles
with no shared vertex, so per-vertex is the unit the question is asked in.  Volume and geometry
counters are printed per FRAME (`rate / fps`, the fps from the arm's own run.txt), which is the
only comparable scale across a 12x range of frame rates; the `spread` row is max/min over the
arms and must read 1.00 for the rest of the table to mean anything.  Misspelt/absent counters
print `MISSING`, never 0 - `fdperf_sections.py` owns the reading rules and its docstring explains
why (`BV` half discarded, wrapped deltas dropped).

What this cannot show: each arm is one run, so the table cannot separate a real effect from
run-to-run noise; the only scale it has is the within-run window spread, printed for the six
tested columns and a lower bound on the noise.  A difference smaller than both arms' spread is
not a measurement.  And the first thing the table checks is whether the pass bins at all: if
`VSC_INPUT_TILES` is 0 in every window the pass is sysmem, where `VPC_VPCRAM_FULL` read 0 in the
23.11 smoke run against 50-71 % in the game, so the prop arms cannot move the counter under test
regardless of what the hardware does with the registers (journal 40.35, queue 35).
"""
