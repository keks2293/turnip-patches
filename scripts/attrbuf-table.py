import glob
import os
import re
import statistics as st
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fdperf_sections import load  # noqa: E402

MISSING = "MISSING"
CLK = "PERF_CP_ALWAYS_COUNT"

# The profile: every column the cfg programs, with the unit its question is asked in, split in
# two blocks so neither table runs off a terminal.  The six TESTED columns below are the ones whose
# movement is the answer; the rest are context (who waits for whom, whether the L2 or the pixel
# side is involved) and the equal-volume controls.
PROFILE_VERTEX = [
    ("VPC busy",    "PERF_VPC_BUSY_CYCLES",                "cycles"),
    ("VPC work",    "PERF_VPC_WORKING_CYCLES",             "cycles"),
    ("WIT full",    "PERF_VPC_WIT_FULL_CYCLES",            "cycles"),
    ("VPCRAMfull",  "PERF_VPC_VPCRAM_FULL_CYCLES",         "cycles"),
    ("LM full",     "PERF_VPC_LM_FULL_WAIT_FOR_INTP_END",  "cycles"),
    ("VPCRAM/vtx",  "PERF_VPC_NUM_VPCRAM_WRITE",           "vertex"),
    ("VFDstallVPC", "PERF_VFD_STALL_CYCLES_VPC_ALLOC",     "cycles"),
    ("VFD busy",    "PERF_VFD_BUSY_CYCLES",                "cycles"),
    ("attrB/vtx",   "PERF_VFD_DECODED_ATTRIBUTE_BYTES",    "vertex"),
    ("attr/vtx",    "PERF_VFD_NUM_ATTRIBUTES",             "vertex"),
]

PROFILE_CONTEXT = [
    ("PCstallVFD",  "PERF_PC_STALL_CYCLES_VFD",            "cycles"),
    ("PCstallVPC",  "PERF_PC_STALL_CYCLES_VPC",            "cycles"),
    ("UCHE busy",   "PERF_UCHE_BUSY_CYCLES",               "cycles"),
    ("UCHE arbt",   "PERF_UCHE_STALL_CYCLES_ARBITER",      "cycles"),
    ("UCHESPread",  "PERF_UCHE_READ_REQUESTS_SP",          "rate"),
    ("UCHEVPCwr",   "PERF_UCHE_WRITE_REQUESTS_VPC",        "rate"),
    ("SP busy",     "PERF_SP_BUSY_CYCLES",                 "cycles"),
]

TESTED = [
    ("VPCRAM full", "PERF_VPC_VPCRAM_FULL_CYCLES",        "cycles"),
    ("WIT full",    "PERF_VPC_WIT_FULL_CYCLES",           "cycles"),
    ("LM full",     "PERF_VPC_LM_FULL_WAIT_FOR_INTP_END", "cycles"),
    ("VPC working", "PERF_VPC_WORKING_CYCLES",            "cycles"),
    ("VPCRAM/vtx",  "PERF_VPC_NUM_VPCRAM_WRITE",          "vertex"),
    ("VFD stallVPC","PERF_VFD_STALL_CYCLES_VPC_ALLOC",    "cycles"),
]

CONTROLS = [
    ("verts",   "PERF_VFD_TOTAL_VERTICES"),
    ("ia_vert", "PERF_PC_IA_VERTICES"),
    ("vs_inv",  "PERF_PC_VS_INVOCATIONS"),
    ("ia_prim", "PERF_PC_IA_PRIMITIVES"),
    ("in_prim", "PERF_TSE_INPUT_PRIM"),
    ("tiles",   "PERF_VSC_INPUT_TILES"),
    ("tag_ck",  "PERF_PC_TAG_CHECKED_VERTICES"),
    ("hits",    "PERF_PC_VERTEX_HITS"),
]

NUM_CCU = 6  # freedreno_devices.py:1241 (GPUId 740 / FD740 / X1-85), same as the runner


def read_meta(path):
    """`key: value` lines of meta.txt, with or without the `# ` the hand-curated smoke file has."""
    meta = {}
    p = os.path.join(path, "meta.txt")
    if not os.path.exists(p):
        return meta
    for line in open(p, errors="replace"):
        line = line.strip()
        if line.startswith("#"):
            line = line[1:].strip()
        m = re.match(r"([a-z_]+):\s+(.*)$", line)
        if m:
            meta.setdefault(m.group(1), m.group(2))
    return meta


def read_run(path):
    """fps and the render-target hash from the probe's own run.txt."""
    out = {}
    p = os.path.join(path, "run.txt")
    if not os.path.exists(p):
        return out
    for line in open(p, errors="replace"):
        parts = line.split()
        if len(parts) < 2:
            continue
        if parts[0] == "fps":
            out["fps"] = parts[1]
        elif parts[0] == "hash":
            out["hash"] = parts[1]
    return out


def arm_of(path):
    """One curated directory as an arm: identity, the env that separates prop from ctrl, pairing hints."""
    meta = read_meta(path)
    run = read_run(path)
    env = meta.get("env", "")
    m = re.search(r"gmem_vpc_attr_buf_size=(\d+)", env)
    size = int(m.group(1)) if m else None
    lm = re.search(r"--loop=(\d+)", meta.get("probe", ""))
    loop = int(lm.group(1)) if lm else 0
    gk = meta.get("gmem_kernel", "").strip()
    gk = int(gk) if gk.isdigit() else None
    tm = re.match(r"(\d+)", meta.get("tu_gmem", ""))
    tu_gmem = int(tm.group(1)) if tm else None
    dm = re.search(r"sha256[ =]([0-9a-f]{12})", meta.get("driver", ""))
    fps = run.get("fps")
    try:
        fps = float(fps)
    except (TypeError, ValueError):
        fps = None
    return {
        "path": path,
        "name": os.path.basename(os.path.normpath(path)),
        "fps": fps,
        "hash": run.get("hash", MISSING),
        "driver": dm.group(1) if dm else MISSING,
        "loop": loop,
        "size": size,
        "tu_gmem": tu_gmem,
        "gmem_kernel": gk,
        "meta": meta,
    }


def med_rate(samples, name):
    """Median of one counter's window deltas, millions per second."""
    v = [s[name] for s in samples if s.get(name) is not None]
    return st.median(v) / 1e6 if v else MISSING


def med_ratio(samples, num, den):
    """Median of a per-window quotient, the denominator from the same window (never med/med)."""
    v = [s[num] / s[den] for s in samples
         if s.get(num) is not None and s.get(den)]
    return st.median(v) if v else MISSING


def value(samples, name, unit, fps):
    """One counter in the unit its question is asked in; MISSING when the dump lacks it."""
    if unit == "cycles":
        return med_ratio(samples, name, CLK)
    if unit == "vertex":
        return med_ratio(samples, name, "PERF_VFD_TOTAL_VERTICES")
    if unit == "frame":
        r = med_rate(samples, name)
        return r / fps if fps and not isinstance(r, str) else MISSING
    return med_rate(samples, name)


def relspread(samples, name, unit, fps):
    """(max - min) / median of the same quantity over the arm's windows, in percent.

    The only noise scale one run can offer; the between-run scatter is unmeasured.
    """
    vals = []
    for s in samples:
        if unit == "cycles":
            if s.get(name) is None or not s.get(CLK):
                continue
            vals.append(s[name] / s[CLK])
        elif unit == "vertex":
            if s.get(name) is None or not s.get("PERF_VFD_TOTAL_VERTICES"):
                continue
            vals.append(s[name] / s["PERF_VFD_TOTAL_VERTICES"])
        else:
            if s.get(name) is None:
                continue
            vals.append(s[name])
    if len(vals) < 2:
        return MISSING
    m = st.median(vals)
    if not m:
        return "all 0" if max(vals) == 0 else "0 seen"
    return 100.0 * (max(vals) - min(vals)) / m


def fmt(v, digits=3):
    if isinstance(v, str):
        return v
    if v is None:
        return MISSING
    if abs(v) >= 1000:
        return "%.0f" % v
    return "%.*f" % (digits, v)


def signed(v, digits=3, suffix=""):
    if isinstance(v, str) or v is None:
        return MISSING
    return "%+.*f%s" % (digits, v, suffix)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("arms", nargs="*", default=None,
                    help="curated arm directories (default: results/synthetics/attrbuf/*/)")
    ap.add_argument("--pair", metavar="PROP", default=None,
                    help="print only the pair whose prop arm is named PROP")
    args = ap.parse_args()

    dirs = args.arms or sorted(glob.glob("results/synthetics/attrbuf/*/"))
    dirs = [d for d in dirs if os.path.exists(os.path.join(d, "fdperf-raw.txt"))]
    if not dirs:
        print("no curated arms under results/synthetics/attrbuf/ - run scripts/run-attrbuf-sweep.sh")
        return 1

    arms = [arm_of(d) for d in sorted(dirs)]

    def order(a):
        """base, then each buffer size with its control before its prop; the loop regime last."""
        m = re.match(r"ctrl-(\d+)k", a["name"])
        buffer = a["size"] or (int(m.group(1)) * 1024 // NUM_CCU if m else 0)
        return (a["loop"], buffer, 1 if a["size"] else 0, a["name"])

    arms.sort(key=order)
    by_name = {a["name"]: a for a in arms}

    # pair prop(S) with ctrl(6S), same loop regime; the name carries the arithmetic, meta verifies it
    pairs, unpaired = [], []
    for p in arms:
        if not p["size"]:
            continue
        ctrl_name = "ctrl-%dk" % (NUM_CCU * p["size"] // 1024)
        if p["loop"]:
            ctrl_name += "-loop%d" % p["loop"]
        c = by_name.get(ctrl_name)
        if c is None:
            unpaired.append((p, ctrl_name))
            continue
        want = NUM_CCU * p["size"]
        if p["gmem_kernel"] is None or c["tu_gmem"] is None:
            note = "UNVERIFIED (no gmem_kernel: queue 36)"
        elif c["tu_gmem"] != p["gmem_kernel"] - want:
            note = "MISMATCH (ctrl TU_GMEM != gmem_kernel - 6S)"
        elif "TU_FORCE_PROPS=has_gmem_vpc_attr_buf" not in p["meta"].get("env", ""):
            note = "MISMATCH (prop env has no TU_FORCE_PROPS)"
        else:
            note = "ok"
        pairs.append((p, c, note))
    pairs.sort(key=lambda x: (x[0]["loop"], x[0]["size"]))

    print("# The VPC attribute-buffer carve-out on A740: prop(S) against a TU_GMEM control of the")
    print("# same usable GMEM (scripts/run-attrbuf-sweep.sh, tools/fdperf/fdperf.cfg-attrbuf).")
    print("# regenerate: scripts/attrbuf-table.py [arm dirs] | tee results/synthetics/attrbuf/table.txt")
    print("# arms:       %s" % ", ".join(a["name"] for a in arms))
    print("# values:     cycles/clock = counter / that window's CP_ALWAYS_COUNT; /vtx = counter /")
    print("#               VFD_TOTAL_VERTICES in the same window; M/s = medians of per-second")
    print("#               deltas; per-frame = rate / the arm's own fps.  MISSING = not programmed.")
    print("# noise:      each arm is one run; `spread` is (max-min)/median over its windows and is")
    print("#               a LOWER bound on the noise.  A difference inside it is not a measurement.")
    print()

    # ---- identity: is the pair a pair? -----------------------------------------------------------
    print("arms - the pair is checked against these two lines, not against the directory names")
    print("%-17s %-7s %-7s %-17s %-6s %-8s %-12s %-24s"
          % ("arm", "fps", "loop", "driver", "prop S", "TU_GMEM", "gmem_kernel", "paired with"))
    for a in arms:
        pair = next((("%s %s" % (c["name"], note)) for p, c, note in pairs if p is a), "-")
        print("%-17s %-7s %-7d %-17s %-6s %-8s %-12s %-24s"
              % (a["name"], fmt(a["fps"], 2), a["loop"], a["driver"],
                 a["size"] if a["size"] else "-",
                 a["tu_gmem"] if a["tu_gmem"] is not None else "unset",
                 a["gmem_kernel"] if a["gmem_kernel"] is not None else MISSING,
                 pair))
    for p, wanted in unpaired:
        print("  %s: no %s - its difference to base mixes the register writes with the %d KiB carve"
              % (p["name"], wanted, NUM_CCU * p["size"] // 1024))
    if not pairs:
        print("  no verified pair in these directories; only the profile below is printable")
    hashes = {a["hash"] for a in arms if a["hash"] != MISSING}
    if len(hashes) > 1:
        print("  WARNING: %d different render-target hashes across the arms - the arms did not draw"
              " the same picture" % len(hashes))

    loaded = {}
    for a in arms:
        samples, _u, dropped = load(os.path.join(a["path"], "fdperf-raw.txt"))
        loaded[a["name"]] = (samples, dropped)

    # ---- did the pass bin at all? ----------------------------------------------------------------
    print()
    print("mode - a sysmem pass never allocates a bin, so the GMEM registers under test are not in")
    print("play and VPC_VPCRAM_FULL read 0 in the 23.11 smoke run (journal 40.35, queue 35)")
    for a in arms:
        tiles = [s.get("PERF_VSC_INPUT_TILES") for s in loaded[a["name"]][0]
                 if s.get("PERF_VSC_INPUT_TILES") is not None]
        if not tiles:
            mode = MISSING
        elif any(tiles):
            mode = "binned (%d/%d windows with tiles)" % (sum(1 for t in tiles if t), len(tiles))
        else:
            mode = "SYSMEM (tiles 0 in %d/%d windows)" % (len(tiles), len(tiles))
        print("  %-17s %s" % (a["name"], mode))

    # ---- the profile ----------------------------------------------------------------------------
    print()
    print("the profile - medians in each column's own unit.  cyc/clk = counter / that window's")
    print("CP_ALWAYS_COUNT, so busy columns are 0..1 and counters that count across lanes exceed 1")
    print("(VFD 11.6, SP 11.9 here); /vtx = per delivered vertex; M/s = per wall second.")
    for title, cols in (("the vertex tract", PROFILE_VERTEX),
                        ("who waits, and whether the L2 or the pixel side is involved",
                         PROFILE_CONTEXT)):
        print()
        print(title)
        row = "%-17s %-6s" + " %10s" * len(cols)
        print(row % (("arm", "fps") + tuple(l for l, _c, _u in cols)))
        print(row % (("", "") + tuple({"cycles": "cyc/clk", "vertex": "/vtx", "rate": "M/s"}[u]
                                      for _l, _c, u in cols)))
        print("-" * len(row % (("arm", "fps") + tuple(l for l, _c, _u in cols))))
        for a in arms:
            samples, _dr = loaded[a["name"]]
            vals = [fmt(value(samples, c, unit, a["fps"]), 3) for _label, c, unit in cols]
            print((row) % ((a["name"], fmt(a["fps"], 2)) + tuple(vals)))

    # ---- the tested columns, with the only noise scale one run offers ------------------------------
    print()
    print("within-run spread of the six tested columns - (max-min)/median over the arm's windows, %.")
    print("Between-run scatter is not measurable here; a prop-ctrl difference inside this is not a")
    print("measurement.")
    print("%-17s" % "arm" + "".join(" %12s" % l[:12] for l, _c, _u in TESTED))
    print("-" * (14 + 13 * len(TESTED)))
    for a in arms:
        samples, _dr = loaded[a["name"]]
        line = "%-17s" % a["name"]
        for _label, c, unit in TESTED:
            line += " %12s" % fmt(relspread(samples, c, unit, a["fps"]), 2)
        print(line)

    # ---- the decision: only inside a pair ---------------------------------------------------------
    print()
    print("prop - ctrl, per pair.  Cycles columns are the absolute difference of two cycles/clock")
    print("ratios (1.000 = one whole core); /vtx and fps are relative, % of the control.  A pair")
    print("marked UNPAIRED has no same-TU_GMEM control and is deliberately not computed.")
    print("%-24s %10s %10s %10s %10s %10s %10s %9s"
          % ("pair", "VPCRAMfull", "WITfull", "LMfull", "VPCworking", "VPCRAM/vtx", "VFDstallVPC", "fps"))
    print("%-24s %10s %10s %10s %10s %10s %10s %9s"
          % ("", "cyc/clk", "cyc/clk", "cyc/clk", "cyc/clk", "% vs ctrl", "cyc/clk", "% vs ctrl"))
    print("-" * 101)
    shown = 0
    for p, c, note in pairs:
        if args.pair and p["name"] != args.pair:
            continue
        shown += 1
        ps, _pd = loaded[p["name"]]
        cs, _cd = loaded[c["name"]]
        cells = []
        for _label, name, unit in TESTED:
            a = value(cs, name, unit, c["fps"])
            b = value(ps, name, unit, p["fps"])
            if isinstance(a, str) or isinstance(b, str):
                cells.append(MISSING)
            elif unit == "vertex":
                cells.append(signed(100.0 * (b - a) / a, 1) if a else MISSING)
            else:
                cells.append(signed(b - a, 3))
        if c["fps"] and p["fps"]:
            fpsd = signed(100.0 * (p["fps"] - c["fps"]) / c["fps"], 1)
        else:
            fpsd = MISSING
        print("%-24s %10s %10s %10s %10s %10s %10s %9s"
              % ("%s / %s" % (p["name"], c["name"]), cells[0], cells[1], cells[2], cells[3],
                 cells[4], cells[5], fpsd))
        if note != "ok":
            print("  %s: pair arithmetic %s" % (p["name"], note))
    for p, wanted in unpaired:
        if args.pair and p["name"] != args.pair:
            continue
        shown += 1
        print("%-24s %10s %10s %10s %10s %10s %10s %9s"
              % (p["name"], "UNPAIRED", "", "", "", "", "", ""))
    if not shown:
        print("  no pair to print")

    # ---- equal-volume controls, per frame ---------------------------------------------------------
    print()
    print("controls - per FRAME, in millions per frame (M/s / the arm's own fps): the arms must agree")
    print("or the differences above are the picture, not the registers.  `spread` is max/min over the")
    print("arms, 1.00 = equal.")
    print("%-17s" % "arm" + "".join(" %9s" % h for h, _c in CONTROLS))
    print("-" * (14 + 10 * len(CONTROLS)))
    per_frame = {}
    for a in arms:
        samples, _dr = loaded[a["name"]]
        line = "%-17s" % a["name"]
        for _h, c in CONTROLS:
            v = value(samples, c, "frame", a["fps"])
            per_frame.setdefault(c, []).append(v)
            line += " %9s" % fmt(v, 1)
        print(line)
    line = "%-17s" % "spread"
    for _h, c in CONTROLS:
        nums = [v for v in per_frame[c] if not isinstance(v, str)]
        if len(nums) < 1:
            line += " %9s" % MISSING
        elif len(nums) < 2:
            line += " %9s" % "-"
        elif min(nums) == 0:
            line += " %9s" % ("all 0" if max(nums) == 0 else "0 seen")
        else:
            line += " %9.2f" % (max(nums) / min(nums))
    print(line)

    # ---- the accidental PC 19/39 calibration ------------------------------------------------------
    print()
    print("PC 19 and 39 - the probe's mesh is non-indexed, so the honest reading is checked ~ all IA")
    print("vertices and hits ~ 0 (journal 40.33, queue 31); anything else means the names do not")
    print("mean what they say.  Per frame, in millions, as in the controls table.")
    for a in arms:
        samples, _dr = loaded[a["name"]]
        ck = value(samples, "PERF_PC_TAG_CHECKED_VERTICES", "frame", a["fps"])
        ht = value(samples, "PERF_PC_VERTEX_HITS", "frame", a["fps"])
        ia = value(samples, "PERF_PC_IA_VERTICES", "frame", a["fps"])
        r = (ht / ck) if not isinstance(ht, str) and not isinstance(ck, str) and ck else MISSING
        print("  %-17s checked %-10s hits %-8s ia %-10s hits/checked %s"
              % (a["name"], fmt(ck, 1), fmt(ht, 1), fmt(ia, 1), fmt(r, 4)))

    # ---- what was thrown away ---------------------------------------------------------------------
    any_drop = {a["name"]: loaded[a["name"]][1] for a in arms if loaded[a["name"]][1]}
    if any_drop:
        print()
        print("deltas thrown away as wrapped or [invalid] (scripts/fdperf_sections.py):")
        for name, dr in any_drop.items():
            print("  %-17s %s" % (name, ", ".join("%s=%d" % kv for kv in sorted(dr.items()))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
