#!/bin/bash
# Generate vpc_attrbuf_spv.h from vpc_attrbuf.vert and vpc_attrbuf.frag.
#
# Run in the glslang container, the same way scripts/gen-tp-write-spv.sh does:
#   podman run --rm -v "$PWD/tests:/work:Z" \
#       localhost/mesa-build-fedora44-wsi-glslang-vulkan bash -c 'cd /work && bash gen-vpc-attrbuf-spv.sh'
#
# The .h is committed, like tp_write_spv.h: nothing on this machine compiles GLSL, and a
# reader who only checks out the repository still gets a buildable probe.
set -euxo pipefail
cd /work

# $1 = spv file, $2 = C symbol
emit() {
    echo "static const uint32_t $2[] = {"
    od -A n -t u4 -v "$1" | tr -s ' \t' ' ' | sed 's/^ //; s/ $//; s/ /, /g; s/$/,/' | sed '$ s/,$//'
    echo "};"
}

glslangValidator -V vpc_attrbuf.vert -o /tmp/vpc_attrbuf_vert.spv
glslangValidator -V vpc_attrbuf.frag -o /tmp/vpc_attrbuf_frag.spv

{
    echo "/* Generated by scripts/gen-vpc-attrbuf-spv.sh from vpc_attrbuf.{vert,frag}"
    echo " * (glslangValidator -V, spec constant uLoop left unset: the probe supplies it)."
    echo " * Do not edit. */"
    emit /tmp/vpc_attrbuf_vert.spv vpc_attrbuf_vert_spv
    emit /tmp/vpc_attrbuf_frag.spv vpc_attrbuf_frag_spv
} > /work/vpc_attrbuf_spv.h

head -3 /work/vpc_attrbuf_spv.h
wc -l /work/vpc_attrbuf_spv.h
